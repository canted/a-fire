const files = fixtures.map(({ id, filename, frequency }, index) => {
  const path = resolve(directory, filename);
  execFileSync("ffmpeg", ["-v", "error", "-y", "-f", "lavfi", "-i", `sine=frequency=${frequency}:sample_rate=44100:duration=25`, "-af", "volume=0.25,afade=t=in:d=0.1,afade=t=out:st=24.9:d=0.1", "-map_metadata", "-1", "-c:a", "libmp3lame", "-b:a", "160k", "-threads", "1", path]);
  const durationSeconds = Number(execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "default=noprint_wrappers=1:nokey=1", path], { encoding: "utf8" }).trim());
  return { id, title: `Synthetic study ${index + 1} (${frequency} Hz)`, filename, url: `/storybook/audio/${filename}`, durationSeconds, encoding: "Synthetic sine tone; MP3 160 kbps, 44.1 kHz mono", outputSha256: createHash("sha256").update(readFileSync(path)).digest("hex") };
});
const calibration = resolve(directory, "calibration.wav");
const manifest = { provenance: "Synthetic test signals generated by this script; no source recordings or private user media.", excerptPolicy: "25-second generated tones. Legacy filenames are retained solely for fixture compatibility.", files, calibration: { filename: "calibration.wav", durationSeconds: 12, outputSha256: createHash("sha256").update(readFileSync(calibration)).digest("hex"), transformed: false } };
writeFileSync(resolve(directory, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
console.log(`Generated ${files.length} synthetic audio fixtures.`);
